"""results/resampling.json and docs/resampling/RESULTS.md: the resampling study's run
(runs/resampling), analyzed as docs/RESAMPLING_PREREGISTRATION.md, section 4, specifies.

- **The numbers are the frozen analysis's.** results/resampling.json is the report that
  opt_agent.resampling_report.build returns (the analysis whose hash docs/resampling/FREEZE.json
  records), unchanged, on the run's results.jsonl and the follow-up's keys, written as its
  main() writes it (json.dumps, indent 1, a newline at the end). Nothing here computes a
  reported number.
- **But this writes it, not main()** (deviation 1, docs/resampling/DEVIATIONS.md): the frozen
  main() stops at json.dumps, because R2's `detected` is a numpy bool (stats.mcnemar_exact
  returns a numpy float when p < 1, and comparing one gives a numpy bool). Here json's
  `default` writes each numpy scalar as the Python value it holds; json calls it only for what
  it can't write itself.
- **RESULTS.md** is rendered from results/resampling.json alone: the primary outcome first,
  then the deviations, then R1's effect, R2 and what's reported without a test.

Building needs the frozen inputs (resampling.problems runs resampling_freeze.check) and
LLM4OR's data, so once HEAD's package has moved on, it runs only in the tag's own tree
(scripts/reproduce.py); rendering needs neither. No API calls, no timestamps: the same inputs
give the same bytes.

Run:  python scripts/resampling_results.py            # build results/resampling.json, render
      python scripts/resampling_results.py --render   # RESULTS.md from the committed JSON
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "runs" / "resampling"
OUT = ROOT / "results" / "resampling.json"
RESULTS_MD = ROOT / "docs" / "resampling" / "RESULTS.md"


# ---- building ---------------------------------------------------------------------------


def build(run: Path = RUN) -> dict:
    """The frozen analysis's report: resampling_report.build, called as its main() calls it."""
    from opt_agent import resampling, resampling_report  # the frozen inputs and the data
    from opt_agent.evaluate import latest_items

    return resampling_report.build(latest_items(run / "results.jsonl"), resampling.problems())


def python_value(value: object) -> object:
    """json's `default`: a numpy scalar as the Python value it holds (deviation 1)."""
    if type(value).__module__ == "numpy" and hasattr(value, "item"):
        return value.item()
    raise TypeError(f"Object of type {type(value).__name__} is not JSON serializable")


def dumps(report: dict) -> str:
    """The report as the frozen main() writes it, numpy scalars aside."""
    return json.dumps(report, indent=1, default=python_value) + "\n"


# ---- rendering --------------------------------------------------------------------------


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def interval(rate: dict) -> str:
    low, high = rate["wilson95"]
    return f"{100 * low:.1f}–{100 * high:.1f}%"


def p(x: float) -> str:
    """Two significant digits, as 0.00098, 2.3e-6 or 4.0e-6."""
    text = f"{x:#.2g}"
    if "e" in text:
        mantissa, exponent = text.split("e")
        text = f"{mantissa}e{int(exponent)}"
    return text


def share(rate: dict) -> str:
    return f"{rate['k']} of {rate['n']} | {pct(rate['value'])} ({interval(rate)})"


def render(data: dict) -> str:
    r1, r2, again, abstain = data["r1"], data["r2"], data["r1_without_disputed"], data["abstention"]
    t = r1["table"]
    verdict = "supported" if r1["supported"] else "not supported"
    return "\n".join([
        "# The resampling study: results",
        "",
        "Generated by `scripts/resampling_results.py` from `results/resampling.json`, the frozen",
        "analysis's report (`src/opt_agent/resampling_report.py`, by its hash in",
        "`docs/resampling/FREEZE.json`); don't edit by hand. Every number here is in that file,",
        "and a test checks it. The study:",
        "[the pre-registration](../RESAMPLING_PREREGISTRATION.md);",
        "its hypothesis came from the exploratory disagreement detector",
        "([`docs/analysis/disagreement_detector.md`](../analysis/disagreement_detector.md)).",
        "",
        f"## Primary outcome: R1 is {verdict}",
        "",
        "R1: among the answers the agent would report, a flagged answer is wrong more often than",
        "an unflagged one. The units are single-shot sample 3, one per problem, where it's",
        f"verified: {r1['units']} of the {data['problems']} problems (the other "
        f"{data['problems_without_a_unit']} gave no verified answer). A unit is flagged when",
        "samples 3 to 7 don't all agree or the no-solver baseline's answer differs, and it's a",
        "silent failure when it's wrong. Fisher's exact test, one-sided, on flagged by silent",
        f"failure: **p = {p(r1['p_value'])}, so R1 is {verdict}**",
        "(pre-registered: supported if p is below alpha 0.05).",
        "",
        "| unit | silent failure | right |",
        "|---|---:|---:|",
        f"| flagged | {t['flagged_silent']} | {t['flagged_right']} |",
        f"| not flagged | {t['unflagged_silent']} | {t['unflagged_right']} |",
        "",
        "## Deviations",
        "",
        "One, recorded in [`DEVIATIONS.md`](DEVIATIONS.md): the frozen analysis computed every",
        "number, but its `main()` couldn't write this file, because R2's verdict was a numpy bool,",
        "which `json` can't write. `scripts/resampling_results.py` writes the same report, each",
        "numpy value as the Python value it holds. No number changes.",
        "",
        "## R1's effect (reported whatever p is)",
        "",
        "With one unit per problem, the units are independent, so the 95% Wilson intervals are",
        "honest.",
        "",
        "| | of | share (95% Wilson) |",
        "|---|---|---|",
        f"| base rate: silent failures, of the units | {share(r1['base_rate'])} |",
        f"| flag rate: flagged, of the units | {share(r1['flag_rate'])} |",
        f"| **precision:** silent failures, of the flagged | {share(r1['precision'])} |",
        f"| **recall:** flagged, of the silent failures | {share(r1['recall'])} |",
        "",
        f"Precision is {r1['precision_over_base_rate']:.2f} times the base rate.",
        "",
        "## R2 (secondary): the majority of five samples against one",
        "",
        f"On all {r2['problems']} problems, sample 3 alone was right on {r2['one_sample_right']}, "
        "and the majority of samples 3 to 7",
        "(an answer at least 3 of the five give, counting verified answers only) on "
        f"{r2['majority_right']}:",
        f"{r2['only_majority_right']} problems only the majority got right, and "
        f"{r2['only_one_sample_right']} only the one sample. Exact McNemar, two-sided:",
        f"p = {p(r2['p_value'])}, **{'detected' if r2['detected'] else 'not detected'}**.",
        "",
        "## Reported without a test",
        "",
        "- **Without the 13 disputed problems** (secondary, no claim; an LLM judge flagged their",
        f"  keys, not verified by a person): {again['units']} units, p = {p(again['p_value'])}.",
        f"  Base rate {pct(again['base_rate']['value'])} ({again['base_rate']['k']} of "
        f"{again['base_rate']['n']}); precision {pct(again['precision']['value'])}",
        f"  ({again['precision']['k']} of {again['precision']['n']}, "
        f"{interval(again['precision'])}); recall {pct(again['recall']['value'])}",
        f"  ({again['recall']['k']} of {again['recall']['n']}, {interval(again['recall'])}); "
        f"precision {again['precision_over_base_rate']:.2f} times the base rate.",
        "- **Abstaining on a flag:** withholding the flagged units would make "
        f"{abstain['silent_made_loud']} silent",
        f"  failures loud and lose {abstain['right_lost']} right answers; "
        f"{abstain['silent_left']} silent failures would still get through.",
        "",
        "## The run",
        "",
        f"`runs/resampling`: {data['problems_complete']} of {data['problems']} problems complete, "
        f"and {data['cells_errored']} cells errored.",
        "What it paid, and how the run went: [`DEVIATIONS.md`](DEVIATIONS.md), the notes on the",
        "run.",
        "",
    ])  # fmt: skip


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="The resampling study's results and write-up.")
    parser.add_argument("--render", action="store_true",
                        help="only render RESULTS.md from the committed JSON")  # fmt: skip
    args = parser.parse_args(argv)
    if not args.render:
        OUT.write_text(dumps(build()))
    RESULTS_MD.write_text(render(json.loads(OUT.read_text())))
    print(f"wrote {OUT.relative_to(ROOT)} and {RESULTS_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
