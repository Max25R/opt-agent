"""Split the follow-up benchmarks into dev and follow-up test, once, by a recorded seed.

Reads only each ComplexLP line's `id` and counts IndustryOR's lines: no problem text or
answer is read, so the split can't depend on them. ComplexLP: 25 dev, 86 follow-up test.
Every problem's place comes from the SHA-256 of "<seed>:<id>": the 25 lowest go to dev.
That is reproducible on any machine and Python version, unlike a library shuffle.
IndustryOR has no ids, so its problems are named by line number (1 to 42); all of them are
follow-up test.

Writes data/followup/split.json and docs/FOLLOWUP_SPLIT.md (which records the JSON's
SHA-256). Refuses to overwrite a different split: the split is made once.

Run:  python scripts/followup_split.py
"""

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "external" / "llm4or-clean"
SPLIT = ROOT / "data" / "followup" / "split.json"
DOC = ROOT / "docs" / "FOLLOWUP_SPLIT.md"
SEED = 20261109
DEV_SIZE = 25
SOURCE = {
    "repository": "https://github.com/LLM4OR/LLM4OR",
    "commit": "75962df5ddf531906fda76f8708c658114e63c0e",
    "files": {
        "Mamo_complex_lp_clean.jsonl": (
            "28e10dff1146ff635673293b5730abb3d7efa2f7bbe91de60fe67b729dfe7a0d"
        ),
        "IndustryOR.jsonl": "d7c2c05377ade5bc6a401ebf3075f0e00fa91068439761e5b46fa3045ffc19b5",
    },
}
# Seen before the split, during the 2026-11-08 research step (docs/EXTERNAL_DATA.md): Claude
# printed these problems' text, whole or in part. Recorded so the pre-registration can
# decide whether to leave them out of follow-up test scoring.
SEEN = {
    "complexlp": {
        "1": "the first line printed: the start of its question and its answer",
        "193": "a keyword search printed about 240 characters of its question",
        "194": "a keyword search printed about 240 characters of its question",
    },
    "industryor": {
        "1": "the first line printed: its whole question and answer",
        "9": "a keyword search printed about 240 characters of its question",
        "13": "a keyword search printed about 240 characters of its question",
        "38": "a keyword search printed about 240 characters of its question",
    },
}


def rank(problem_id: int | str) -> str:
    return hashlib.sha256(f"{SEED}:{problem_id}".encode()).hexdigest()


def split() -> dict:
    for name, sha in SOURCE["files"].items():
        if hashlib.sha256((DATA / name).read_bytes()).hexdigest() != sha:
            raise ValueError(f"{DATA / name} isn't the copy docs/EXTERNAL_DATA.md records")
    lines = (DATA / "Mamo_complex_lp_clean.jsonl").read_text().splitlines()
    ids = sorted(json.loads(line)["id"] for line in lines if line.strip())
    if len(ids) != len(set(ids)):
        raise ValueError("ComplexLP ids aren't unique")
    dev = sorted(sorted(ids, key=rank)[:DEV_SIZE])
    test = sorted(set(ids) - set(dev))
    industry = (DATA / "IndustryOR.jsonl").read_text().splitlines()
    return {
        "seed": SEED,
        "method": "ComplexLP: the 25 ids with the lowest SHA-256 of '<seed>:<id>' are dev, "
        "the rest follow-up test. IndustryOR: every problem, by line number, is follow-up "
        "test. Only ids and line counts were read.",
        "source": SOURCE,
        "complexlp": {"dev": dev, "test": test},
        "industryor": {
            "dev": [],
            "test": list(range(1, sum(1 for x in industry if x.strip()) + 1)),
        },
        "seen_before_the_split": SEEN,
    }


def dumps(data: dict) -> str:
    return json.dumps(data, indent=1) + "\n"


def doc(data: dict, digest: str) -> str:
    c, i = data["complexlp"], data["industryor"]

    def where(benchmark: str, problem: str) -> str:
        key = int(problem)
        return "dev" if key in data[benchmark]["dev"] else "follow-up test"

    seen = [f"| {b} | {p} | {where(b, p)} | {how} |"
            for b in ("complexlp", "industryor") for p, how in SEEN[b].items()]  # fmt: skip
    return f"""# Follow-up split

Generated by `scripts/followup_split.py`; don't edit by hand. Made once, on 2026-11-09,
before any follow-up pre-registration and before any model ran on these problems.

**The rule.** Nobody, Claude or the pipeline, looks at a follow-up test problem's text or
answer until the follow-up pre-registration is frozen. Building and tuning use the dev split
here, or NL4Opt dev. `opt_agent.followup.load` returns dev problems only and raises `Sealed`
for a test split.

**The data.** LLM4OR's cleaned benchmarks (`docs/EXTERNAL_DATA.md`): repository
`{SOURCE["repository"]}`, commit `{SOURCE["commit"][:7]}`. The split script checks both
files' SHA-256 first.

**The split.** `data/followup/split.json`, SHA-256 `{digest}`.
- **ComplexLP** ({len(c["dev"]) + len(c["test"])} problems): {len(c["dev"])} dev,
  {len(c["test"])} follow-up test. A problem's place comes from the SHA-256 of
  `"{data["seed"]}:<id>"`; the {len(c["dev"])} lowest are dev. Only ids were read.
- **IndustryOR** ({len(i["test"])} problems, named by line number): all follow-up test.

**ComplexLP dev ids:** {", ".join(map(str, c["dev"]))}

**ComplexLP follow-up test ids:** {", ".join(map(str, c["test"]))}

**IndustryOR follow-up test lines:** 1 to {len(i["test"])}

## Seen before the split

During the research step of 2026-11-08, before this split, Claude printed some problems'
text while profiling the benchmarks. It also computed aggregate statistics over every
problem (counts, problem types, mean lengths). These problems were seen:

| benchmark | id or line | split | what was seen |
|---|---|---|---|
{chr(10).join(seen)}

The split doesn't move them, so it stays random. Whether to leave the seen follow-up test
problems out of scoring is for the pre-registration to decide.
"""


def main() -> None:
    data = split()
    text = dumps(data)
    if SPLIT.exists() and SPLIT.read_text() != text:
        sys.exit(f"{SPLIT} exists and differs: the split is made once")
    SPLIT.parent.mkdir(parents=True, exist_ok=True)
    SPLIT.write_text(text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    DOC.write_text(doc(data, digest))
    print(f"Wrote {SPLIT.relative_to(ROOT)} (SHA-256 {digest}) and {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
