"""Write a review sheet of 30 dev problems: text, our model, both optima, notes, review.

Run:  python scripts/dev_walkthrough.py
Writes data/nl4opt/ground_truth/DEV_WALKTHROUGH.md. The selection is deterministic: every
rejected or hand-reviewed dev problem first, then problems that cover each kind of
declaration and note, then the rest in file order.
"""

from opt_agent.ground_truth import GROUND_TRUTH_DIR, Record, integrality_matters, load_records
from opt_agent.schema import Constraint, LPModel, Term

COUNT = 30


def select(records: list[Record]) -> list[Record]:
    chosen = [r for r in records if r.error or r.review]
    covered = {feature for r in chosen for feature in features(r)}
    for r in records:
        if r not in chosen and set(features(r)) - covered:
            chosen.append(r)
            covered |= set(features(r))
    chosen += [r for r in records if r not in chosen]
    return chosen[:COUNT]


def features(record: Record) -> list[str]:
    if record.model is None:
        return []
    kinds = [c.name.split("_", 1)[1] for c in record.model.constraints]
    return kinds + [n.kind for n in record.notes]


def render(records: list[Record]) -> str:
    lines = [
        "# Dev walkthrough: 30 problems to check by hand",
        "",
        "Generated by `python scripts/dev_walkthrough.py`. For each problem, check that the",
        "model says what the text says, then that the answer is plausible.",
        "",
    ]
    for number, r in enumerate(records, 1):
        lines += [f"## {number}. `{r.id}`: {headline(r)}", "", f"> {r.document}", ""]
        if r.error:
            lines += [f"**Rejected:** {r.error}", ""]
        else:
            lines += ["```", *model_lines(r.model), "```", "", answer_line(r), ""]
            lines += [f"- note ({n.kind}): {n.detail}" for n in r.notes]
        if r.review:
            lines += [f"**Hand review ({r.review.verdict}):** {r.review.reason}", ""]
        lines += ["- [ ] the model matches the text", "- [ ] the answer looks right", ""]
    return "\n".join(lines) + "\n"


def headline(r: Record) -> str:
    if r.error:
        return "rejected annotation"
    if r.review:
        return r.review.verdict
    return "integrality changes the answer" if integrality_matters(r) else "ordinary"


def model_lines(model: LPModel) -> list[str]:
    width = max(len(c.name) for c in model.constraints) if model.constraints else 0
    lines = [f"{model.objective.sense}  {expression(model.objective.terms)}"]
    lines += [f"  {c.name:<{width}}  {constraint(c)}" for c in model.constraints]
    return lines + ["  every variable >= 0"]


def constraint(c: Constraint) -> str:
    return f"{expression(c.terms)} {c.sense} {c.rhs:g}"


def expression(terms: list[Term]) -> str:
    parts = [f"{abs(t.coef):g}*[{t.var}]" for t in terms]
    signs = ["-" if t.coef < 0 else "+" for t in terms]
    text = ("-" if signs[0] == "-" else "") + parts[0]
    return text + "".join(f" {s} {p}" for s, p in zip(signs[1:], parts[1:], strict=True))


def answer_line(r: Record) -> str:
    def show(solve) -> str:
        if solve.objective is None:
            return solve.status.value
        values = ", ".join(f"{k} = {v:.4g}" for k, v in solve.values.items())
        return f"{solve.objective:.6g} ({values})"

    return f"**LP:** {show(r.lp)}  \n**IP:** {show(r.ip)}"


if __name__ == "__main__":
    records = select(load_records(GROUND_TRUTH_DIR / "dev.json"))
    (GROUND_TRUTH_DIR / "DEV_WALKTHROUGH.md").write_text(render(records))
    print(f"wrote {len(records)} problems to {GROUND_TRUTH_DIR / 'DEV_WALKTHROUGH.md'}")
